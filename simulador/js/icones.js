const cache = {};

export function icone(nome, classe = '') {
  if (!cache[nome]) {
    const g = GRADES[nome];
    let d = '', seta = '';
    g.forEach((linha, y) => [...linha].forEach((ch, x) => { if (ch === '#') d += `M${x} ${y}h1v1h-1z`; if (ch === 'o') seta += `M${x} ${y}h1v1h-1z`; }));
    const logo = nome === 'logo', px = logo ? 1 : 3;
    cache[nome] = `<svg viewBox="0 0 ${g[0].length} ${g.length}" width="${g[0].length * px}" height="${g.length * px}" shape-rendering="crispEdges" fill="${logo ? '#0040ff' : 'currentColor'}" aria-hidden="true"><path d="${d}"/>${seta ? `<path fill="#fff" d="${seta}"/>` : ''}</svg>`;
  }
  return classe ? cache[nome].replace('<svg ', `<svg class="${classe}" `) : cache[nome];
}
